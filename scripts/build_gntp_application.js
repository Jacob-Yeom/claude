// split "[확인 필요]" placeholders into red runs
function runs(text, opt = {}) {
  const parts = String(text).split(/(\[[^\]]*\])/g).filter((s) => s !== "");
  return parts.map((p) =>
    new TextRun({
      text: p,
      font: FONT,
      size: opt.size || 20,
      bold: opt.bold,
      color: p.startsWith("[") ? RED : opt.color,
      italics: opt.italics,
    })
  );
}
function P(text, opt = {}) {
  return new Paragraph({
    alignment: opt.align || AlignmentType.LEFT,
    spacing: { before: opt.before ?? 0, after: opt.after ?? 40, line: opt.line ?? 276 },
    indent: opt.indent,
    pageBreakBefore: opt.pageBreak,
    children: runs(text, opt),
  });
}
function H1(text) {
  return new Paragraph({
    spacing: { before: 240, after: 120 },
    children: runs(text, { size: 28, bold: true }),
  });
}
function H2(text) {
  return new Paragraph({
    spacing: { before: 200, after: 100 },
    children: runs(text, { size: 24, bold: true }),
  });
}
function H3(text) {
  return new Paragraph({
    spacing: { before: 120, after: 60 },
    children: runs(text, { size: 22, bold: true }),
  });
}
function note(text) {
  return P(text, { size: 16, color: "595959", after: 60 });
}
// bullet-style lines in 개조식 (□ / ㅇ / -) — plain text markers, hanging indent
function L(level, text, opt = {}) {
  const marks = ["□ ", "ㅇ ", "- "];
  const ind = [0, 240, 480];
  return new Paragraph({
    spacing: { before: 0, after: 30, line: 264 },
    indent: { left: ind[level] + 200, hanging: 200 },
    children: runs(marks[level] + text, { size: opt.size || 19, bold: level === 0 && opt.bold }),
  });
}
function cell(content, o = {}) {
  const paras = (Array.isArray(content) ? content : [content]).map((c) =>
    c instanceof Paragraph || c instanceof Table
      ? c
      : new Paragraph({
          alignment: o.align || AlignmentType.LEFT,
          spacing: { before: 10, after: 10, line: 252 },
          children: runs(c, { size: o.size || 18, bold: o.bold }),
        })
  );
  return new TableCell({
    width: { size: o.w, type: WidthType.DXA },
    columnSpan: o.span,
    rowSpan: o.rowSpan,
    verticalAlign: o.v || VerticalAlign.CENTER,
    shading: o.shade ? { type: ShadingType.CLEAR, fill: o.shade === true ? "EDEDED" : o.shade, color: "auto" } : undefined,
    margins: { top: 40, bottom: 40, left: 80, right: 80 },
    children: paras,
  });
}
